/* LS7A2000 user manual V1.3, chapter 20. All DC accesses are 32-bit. */
#ifndef LSDC_REGS_H
#define LSDC_REGS_H

#include <linux/bits.h>

#define LSDC_PIPE_REG(reg, index) ((reg) + (index) * 0x10)
#define LSDC_FB_CONFIG 0x1240
#define LSDC_FB_ADDRESS0 0x1260
#define LSDC_FB_STRIDE 0x1280
#define LSDC_FB_ORIGIN 0x1300
#define LSDC_DITHER_CONFIG 0x1360
#define LSDC_HDISPLAY 0x1400
#define LSDC_HSYNC 0x1420
#define LSDC_VDISPLAY 0x1480
#define LSDC_VSYNC 0x14a0
#define LSDC_CURRENT_LOCATION 0x14c0
#define LSDC_INTERRUPT 0x1570
#define LSDC_FB_ADDRESS1 0x1580
#define LSDC_VSYNC_COUNTER 0x1a00

#define LSDC_FB_RESET BIT(20)
#define LSDC_FB_DMA GENMASK(17, 16)
#define LSDC_FB_GAMMA BIT(12)
#define LSDC_FB_BANK BIT(11)
#define LSDC_FB_CROSS_ROUTE BIT(9)
#define LSDC_FB_ENABLE BIT(8)
#define LSDC_FB_SWITCH BIT(7)
#define LSDC_FB_TILE GENMASK(5, 4)
#define LSDC_FB_FORMAT GENMASK(2, 0)
#define LSDC_FB_ARGB8888 4
#define LSDC_SYNC_INVERT BIT(31)
#define LSDC_SYNC_ENABLE BIT(30)
#define LSDC_IRQ_VSYNC0 BIT(2)
#define LSDC_IRQ_VSYNC1 BIT(0)

/* Cursor registers are not spaced like the display-pipe registers. */
#define LSDC_CURSOR_CONFIG0 0x1520
#define LSDC_CURSOR_CONFIG1 0x1670
#define LSDC_CURSOR_ADDRESS0 0x1530
#define LSDC_CURSOR_ADDRESS1 0x1680
#define LSDC_CURSOR_HIGH0 0x15e0
#define LSDC_CURSOR_HIGH1 0x16e0
#define LSDC_CURSOR_POSITION0 0x1540
#define LSDC_CURSOR_POSITION1 0x1690
#define LSDC_CURSOR_FORMAT GENMASK(1, 0)
#define LSDC_CURSOR_ARGB8888 2
#define LSDC_CURSOR_64 BIT(2)
#define LSDC_CURSOR_ROUTE BIT(4)

#endif
